/**
 * Returns the localized version of a category based on the current language code.
 */
export const getLocalizedCategory = (cat, langCode = 'en') => {
  if (!cat) return null;
  const langPack = DIGITAL_PLAYBOOKS_LOCALIZED[langCode];
  if (!langPack || !langPack.categories[cat.id]) {
    return cat; // Fallback to raw/English category
  }

  const localCat = langPack.categories[cat.id];

  return {
    ...cat,
    title: localCat.title || cat.title,
    summary: localCat.summary || cat.summary,
    immediate_considerations: localCat.immediate_considerations || cat.immediate_considerations,
    response_checklist: (cat.response_checklist || []).map((step, idx) => {
      const localStep = (localCat.response_checklist || [])[idx];
      return localStep ? { ...step, title: localStep.title, detail: localStep.detail } : step;
    }),
    evidence_preservation_tips: localCat.evidence_preservation_tips || cat.evidence_preservation_tips,
    security_privacy_actions: localCat.security_privacy_actions || cat.security_privacy_actions
  };
};

